// Builds generated theme files: compiled CSS, fonts, vendor scripts and the
// `media-image` snippet that renders the campaign images from theme/assets.
import { execFileSync } from "node:child_process";
import { copyFile, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const theme = path.join(root, "theme");
const nm = path.join(root, "node_modules");
const assets = path.join(theme, "assets");

const copies = [
  ["@fontsource-variable/archivo/files/archivo-latin-wght-normal.woff2", "archivo-latin-wght-normal.woff2"],
  ["@fontsource/big-shoulders/files/big-shoulders-latin-700-normal.woff2", "big-shoulders-latin-700-normal.woff2"],
  ["@fontsource/big-shoulders/files/big-shoulders-latin-800-normal.woff2", "big-shoulders-latin-800-normal.woff2"],
  ["gsap/dist/gsap.min.js", "gsap.min.js"],
  ["gsap/dist/ScrollTrigger.min.js", "ScrollTrigger.min.js"],
  ["lenis/dist/lenis.min.js", "lenis.min.js"],
];
for (const [from, to] of copies) await copyFile(path.join(nm, from), path.join(assets, to));

// Generated snippet: {% render 'media-image', key: 'tee-gym-hook', sizes: '50vw', class: '...' %}
const { images } = JSON.parse(await readFile(path.join(root, "scripts/media.json"), "utf8"));
const esc = (s) => s.replace(/'/g, "’");
let cases = "";
for (const img of images) {
  const dims = {};
  for (const s of ["sm", "lg"]) {
    const file = path.join(assets, `media-${img.key}-${s}.webp`);
    if (existsSync(file)) {
      const m = await sharp(file).metadata();
      dims[s] = [m.width, m.height];
    } else {
      const w = Math.min(img.width, s === "sm" ? 800 : 1800);
      dims[s] = [w, Math.round((img.height * w) / img.width)];
    }
  }
  cases += `  {%- when '${img.key}' -%}
    {%- assign w_sm = ${dims.sm[0]} -%}{%- assign w_lg = ${dims.lg[0]} -%}{%- assign h_lg = ${dims.lg[1]} -%}
    {%- assign default_alt = '${esc(img.alt)}' -%}
`;
}
const snippet = `{%- comment -%}
  GENERATED by shopify/scripts/build.mjs from scripts/media.json. Do not edit by hand.
  Renders a campaign image stored in theme/assets at two sizes.
  Params: key, sizes, class, alt (optional, '' for decorative), loading ('lazy' | 'eager'), priority (true for LCP images)
{%- endcomment -%}
{%- case key -%}
${cases}{%- endcase -%}
{%- if alt == nil -%}{%- assign alt = default_alt -%}{%- endif -%}
{%- assign src_sm = 'media-' | append: key | append: '-sm.webp' | asset_url -%}
{%- assign src_lg = 'media-' | append: key | append: '-lg.webp' | asset_url -%}
<img
  src="{{ src_lg }}"
  srcset="{{ src_sm }} {{ w_sm }}w, {{ src_lg }} {{ w_lg }}w"
  sizes="{{ sizes | default: '100vw' }}"
  width="{{ w_lg }}"
  height="{{ h_lg }}"
  alt="{{ alt | escape }}"
  {% if priority %}fetchpriority="high" loading="eager"{% else %}loading="{{ loading | default: 'lazy' }}"{% endif %}
  decoding="async"
  {% if class %}class="{{ class }}"{% endif %}
>
`;
await writeFile(path.join(theme, "snippets/media-image.liquid"), snippet);

const altCases = images.map((img) => `  {%- when '${img.key}' -%}${esc(img.alt)}\n`).join("");
await writeFile(
  path.join(theme, "snippets/media-alt.liquid"),
  `{%- comment -%} GENERATED by shopify/scripts/build.mjs. Prints the description of a bundled campaign image. Params: key {%- endcomment -%}\n{%- case key -%}\n${altCases}{%- endcase -%}\n`,
);

execFileSync(path.join(nm, ".bin/tailwindcss"), ["-i", path.join(root, "src/theme.css"), "-o", path.join(assets, "theme.css"), "--minify"], { stdio: "inherit" });
console.log("built theme assets");
